// Turns the authored expansion files (out-<course>.json) into public/learn/content/bank/<course>.mjs.
// Usage: node tools/build-bank-extension.mjs <dir with out-*.json> [expectedPerCourse=200]
import {readFileSync,readdirSync,writeFileSync,mkdirSync} from 'node:fs';
import {courses} from '../public/learn/courses.mjs';
const dir=process.argv[2],expected=Number(process.argv[3]||200);if(!dir)throw new Error('dir required');
mkdirSync('public/learn/content/bank',{recursive:true});
const files=readdirSync(dir).filter(f=>/^out-.*\.json$/.test(f)),byCourse={};
for(const f of files){const j=JSON.parse(readFileSync(`${dir}/${f}`,'utf8'));byCourse[j.course]??={course:j.course,lessons:{},reviewNotes:[]};Object.assign(byCourse[j.course].lessons,j.lessons);byCourse[j.course].reviewNotes.push(...(j.reviewNotes||[]));}
const problems=[];
// Style normalisation: neutral filler tails on distractors and justification clauses on the correct option are length/style cues.
const TAILS=/\s+(en este momento|por ahora|de inmediato|en ese caso|en esta situación|en el momento|sin demora|hasta nuevo aviso)\.?$/i;
function cleanOptions(options){
 const o=options.map(x=>String(x).trim().replace(TAILS,''));
 const m=o[0].match(/^(.{12,}?),?\s+(?:porque|ya que|dado que|pues)\s+.+$/i);if(m&&!o.slice(1).some(d=>/(,?\s+(porque|ya que|dado que|pues)\s)/i.test(d)))o[0]=m[1];
 return o;
}
for(const [id,data] of Object.entries(byCourse)){
 const c=courses.find(x=>x.id===id);if(!c){problems.push('curso desconocido '+id);continue;}
 let total=0;const out={};
 for(const l of c.lessons){
  const e=data.lessons[l.id];if(!e){problems.push(`${id}: falta la lección ${l.id}`);continue;}
  const qs=e.questions||[];total+=qs.length;
  qs.forEach((q,k)=>{if(!Array.isArray(q.options)||q.options.length!==5||new Set(q.options.map(o=>String(o).trim().toLowerCase())).size!==5)problems.push(`${l.id} #${k+1}: opciones inválidas`);if(!q.prompt||!q.why||q.why.length<40)problems.push(`${l.id} #${k+1}: enunciado o fundamento faltante`);});
  if(!e.theoryAddendum||e.theoryAddendum.split(/\s+/).length<120)problems.push(`${l.id}: ampliación teórica breve`);
  out[l.id]={theoryAddendum:e.theoryAddendum.trim(),questions:qs.map(q=>{const o=cleanOptions(q.options);return [q.prompt.trim(),...o,q.why.trim(),q.skill||l.area||l.title];})};
 }
 if(total!==expected)problems.push(`${id}: ${total} preguntas nuevas (se esperaban ${expected})`);
 writeFileSync(`public/learn/content/bank/${id}.mjs`,`// Expansion bank for ${id}: ${total} additional questions + theory addenda. Original, pending faculty validation. Row: [prompt, correct, d1, d2, d3, d4, why, skill].\nexport default ${JSON.stringify(out,null,1)};\n`);
 console.log(id,total,'preguntas nuevas');
}
if(problems.length){console.error(problems.slice(0,40).join('\n'));process.exit(1);}
const have=readdirSync('public/learn/content/bank').filter(f=>f.endsWith('.mjs')).map(f=>f.replace('.mjs','')).sort();
writeFileSync('public/learn/content/bank.mjs',`// Generated by tools/build-bank-extension.mjs. Merges the expansion banks into the course lessons.
${have.map((id,i)=>`import b${i} from './bank/${id}.mjs';`).join('\n')}
const banks={${have.map((id,i)=>`'${id}':b${i}`).join(',')}};
export function applyBankExtensions(courses){
 for(const c of courses){const bank=banks[c.id];if(!bank)continue;
  for(const l of c.lessons){const e=bank[l.id];if(!e)continue;
   l.workedExamples=l.workedExamples||l.questions.length;
   l.body=(l.body||'')+'\\n\\n'+e.theoryAddendum;
   e.questions.forEach((r,k)=>l.questions.push({id:l.id+'-n'+(k+1),prompt:r[0],options:r.slice(1,6),answer:0,why:r[6],skill:r[7],source:l.source}));}}
}
`);
